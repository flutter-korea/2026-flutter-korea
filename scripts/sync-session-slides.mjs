import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { dict } from '../src/lib/content.js';

const links = JSON.parse(execFileSync('python3', ['scripts/sync-session-slides.py'], { encoding: 'utf8' }));
const slides = {};
for (const row of dict.ko.timetable.tracks.rows) {
  for (const track of ['flutter', 'ai', 'shared']) {
    const speaker = track === 'shared' ? row.speaker : row[track]?.speaker;
    if (!speaker) continue;
    const sheetName = speaker.includes('가애KAAE') ? '전세림' : speaker;
    const url = links[sheetName] || links[`${sheetName} (Google)`];
    if (url) slides[`${row.start}-${track}`] = url;
  }
}
await writeFile('static/session-slides.json', JSON.stringify(slides, null, 2) + '\n');
await writeFile('flutter/lib/content/session_slides.dart', `// Generated by scripts/sync-session-slides.mjs.\nimport 'dart:convert';\n\nfinal Map<String, dynamic> sessionSlides = jsonDecode(r'''${JSON.stringify(slides)}''') as Map<String, dynamic>;\n`);
console.log(`Synced ${Object.keys(slides).length} slide links.`);
